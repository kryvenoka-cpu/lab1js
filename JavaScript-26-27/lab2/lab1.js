/* Завдання 4. Пошук елементів, що не є спільними для двох масивів.

   Дано два масиви. Потрібно знайти елементи, які присутні лише
   в одному з двох масивів, тобто не входять до їхньої спільної частини.

   Функція getNonCommonElements повинна приймати два масиви
   та повертати новий масив із такими елементами.

   Наприклад:
   first  = [1, 2, 3, 4]
   second = [3, 4, 5, 6]

   Результат: [1, 2, 5, 6]
*/
function getNonCommonElements(first, second) {
    const result = [];

    // елементи з first, яких немає в second
    for (let i = 0; i < first.length; i++) {
        if (myIndexOf(second, first[i]) === -1) {
            result.push(first[i]);
        }
    }

    // елементи з second, яких немає в first
    for (let i = 0; i < second.length; i++) {
        if (myIndexOf(first, second[i]) === -1) {
            result.push(second[i]);
        }
    }

    return result;
}
