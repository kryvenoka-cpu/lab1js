function containsBirthDay(numbers, birthDay) {
    // myIndexOf повертає -1, якщо елемента немає. Не -1 — значить знайшли.
    return myIndexOf(numbers, birthDay) !== -1;
}


/* Приклад реалізації аналога методу map().
   Ця функція вже реалізована і наведена як приклад для завдання з filter().
*/
function myMap(array, callback) {
    const result = [];

    for (let i = 0; i < array.length; i++) {
        result.push(callback(array[i], i, array));
    }

    return result;
}


/* Завдання 1. Реалізація аналога методу indexOf().

   Реалізуйте власну функцію, яка працює аналогічно до методу indexOf().

   Функція myIndexOf повинна приймати:
   - array — масив;
   - value — значення для пошуку.

   Функція повинна повернути індекс першого знайденого елемента.
   Якщо значення відсутнє в масиві — повернути -1.

   Не використовуйте вбудований метод Array.prototype.indexOf().
*/
function myIndexOf(array, value) {
    for (let i = 0; i < array.length; i++) {
        if (array[i] === value) {
            return i; // знайшли — повертаємо індекс першого входження
        }
    }

    return -1;
}


/* Завдання 2. Реалізація аналога методу filter().

   Реалізуйте власний аналог методу масивів filter(), використовуючи
   наведений вище myMap() як приклад структури функції.

   Функція myFilter повинна приймати:
   - array — початковий масив;
   - predicate — функцію-предикат.

   predicate(element, index, array) повертає true або false.
   До результуючого масиву потрібно додати лише ті елементи,
   для яких predicate повернув true.

   Не використовуйте вбудований метод Array.prototype.filter().
*/
function myFilter(array, predicate) {
    const result = [];

    for (let i = 0; i < array.length; i++) {
        // predicate отримує елемент, індекс і весь масив — як у filter()
        if (predicate(array[i], i, array)) {
            result.push(array[i]);
        }
    }

    return result;
}


